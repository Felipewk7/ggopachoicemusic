// Helper functions for playlist persistence
function getActiveSongs() {
  const saved = localStorage.getItem("ggopa_custom_songs");
  if (saved) {
    try {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length >= 2) {
        return parsed;
      }
    } catch (e) {
      console.warn("Falha ao ler músicas do localStorage:", e);
    }
  }
  return [...DEFAULT_SONGS];
}

function saveActiveSongs(songs) {
  localStorage.setItem("ggopa_custom_songs", JSON.stringify(songs));
}

function resetToDefaultSongs() {
  localStorage.removeItem("ggopa_custom_songs");
  return [...DEFAULT_SONGS];
}

// Universal Environment Compatibility
